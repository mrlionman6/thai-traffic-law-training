def build_jsonl(pairs, path):
    """แปลง QA_PAIRS เป็นไฟล์ .jsonl โดยแต่ละบรรทัดมี column เดียวชื่อ 'text'"""
    with open(path, "w", encoding="utf-8") as f:
        for pair in pairs:
            text = f"### คำถาม:\n{pair['question']}\n### คำตอบ:\n{pair['answer']}"
            f.write(json.dumps({"text": text}, ensure_ascii=False) + "\n")
    print(f"สร้างไฟล์ {path} จำนวน {len(pairs)} แถว")


def push_dataset_to_hub(local_path, repo_id):
    """สร้าง (ถ้ายังไม่มี) และอัปโหลดไฟล์ .jsonl ขึ้น HuggingFace Dataset Hub"""
    create_repo(repo_id, repo_type="dataset", exist_ok=True)

    api = HfApi()
    api.upload_file(
        path_or_fileobj=local_path,
        path_in_repo="data.jsonl",
        repo_id=repo_id,
        repo_type="dataset",
    )
    print(f"Push dataset ขึ้น https://huggingface.co/datasets/{repo_id} สำเร็จ")


def main():
    build_jsonl(QA_PAIRS, LOCAL_JSONL_PATH)
    push_dataset_to_hub(LOCAL_JSONL_PATH, HF_DATASET_REPO)
    print("\nDone. ตอนนี้ train.py พร้อมดึงข้อมูลจาก HF Hub ไปเทรนได้แล้ว")


if __name__ == "__main__":
    main()
